#!/usr/bin/env bash
# Turn the home-local Buzz bridge on or off, or report its state.
#
# Usage: fm-buzz.sh enable|disable|status
#
# enable   validate config/buzz-bridge.env, write and register the watcher
#          check state/buzz-bridge.check.sh (bin/fm-check-register.sh), create
#          config/buzz-bridge.enabled, and seed the poll cursor to now. The
#          registered check is what makes the watcher poll Buzz and makes
#          supervision required in this home. Seeding last means turning the
#          bridge on reads forward only: mentions the owner sent while it was
#          deliberately off are not ingested or answered on enable, while a
#          request already bound before the off period stays answerable.
# disable  remove config/buzz-bridge.enabled first, so intake and replies stop
#          at once, then unregister the watcher check. Nothing re-enables the
#          bridge: bootstrap, restarts, and updates leave it off until an
#          explicit enable. Pending requests and bindings are kept, never sent.
# status   print on/off, check registration, config validity, the poll cursor,
#          pending Buzz requests, and the last poll diagnostic. Never prints the
#          secret.
#
# A home without config/buzz-bridge.enabled is off; that is the default for any
# home without Buzz configured. docs/configuration.md "Buzz bridge" owns setup.
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
CONFIG="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}"
# shellcheck source=bin/fm-buzz-lib.sh
. "$SCRIPT_DIR/fm-buzz-lib.sh"
# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-check-lib.sh
. "$SCRIPT_DIR/fm-check-lib.sh"

MARKER="$CONFIG/buzz-bridge.enabled"
CHECK="$STATE/$FM_BUZZ_CHECK_ID.check.sh"

usage() {
  echo "usage: fm-buzz.sh enable|disable|status" >&2
}

unregister() {
  FM_HOME="$FM_HOME" FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-unregister.sh" "$FM_BUZZ_CHECK_ID" >/dev/null
}

case "${1:-}" in
  enable)
    [ "$#" -eq 1 ] || { usage; exit 2; }
    command -v jq >/dev/null 2>&1 || { echo "fm-buzz: jq not found" >&2; exit 1; }
    command -v python3 >/dev/null 2>&1 || { echo "fm-buzz: python3 not found" >&2; exit 1; }
    fm_buzz_load_config || { echo "fm-buzz: not enabled: $FM_BUZZ_CONFIG_ERROR" >&2; exit 1; }
    mkdir -p "$STATE" "$CONFIG" || exit 1
    home=$(CDPATH='' cd -- "$FM_HOME" && pwd -P) || exit 1
    tmp=$(umask 077; mktemp "$STATE/.buzz-bridge-check.XXXXXX") || exit 1
    printf '%s\n' '#!/usr/bin/env bash' \
      '# Generated by bin/fm-buzz.sh enable - Buzz bridge poll; retire with bin/fm-buzz.sh disable.' \
      "export FM_HOME=$(printf '%q' "$home")" \
      "exec $(printf '%q' "$FM_ROOT/bin/fm-buzz-poll.sh")" > "$tmp" || { rm -f -- "$tmp"; exit 1; }
    if ! chmod 700 "$tmp" || ! mv -f -- "$tmp" "$CHECK"; then
      rm -f -- "$tmp"
      echo "fm-buzz: cannot write $CHECK" >&2
      exit 1
    fi
    FM_HOME="$FM_HOME" FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-register.sh" "$FM_BUZZ_CHECK_ID" >/dev/null \
      || { unregister; echo "fm-buzz: cannot register the watcher check" >&2; exit 1; }
    printf 'enabled\n' > "$MARKER" \
      || { rm -f -- "$MARKER"; unregister; echo "fm-buzz: cannot write $MARKER" >&2; exit 1; }
    now=${FMX_NOW_OVERRIDE:-$(date +%s)}
    case "$now" in
      ''|*[!0-9]*)
        echo "fm-buzz: warning: enabled, but the clock is unreadable, so the first poll may answer mentions sent while the bridge was off" >&2 ;;
      *)
        jq -cn --argjson since "$now" '{since:$since}' \
          | fmx_private_artifact_publish_stdin "$STATE/buzz" cursor.json 600 \
          || echo "fm-buzz: warning: enabled, but the poll cursor could not be seeded, so the first poll may answer mentions sent while the bridge was off" >&2 ;;
    esac
    echo "buzz bridge: enabled for channel $BUZZ_CHANNEL on $BUZZ_COMMUNITY; the watcher polls it on its next check sweep"
    ;;
  disable)
    [ "$#" -eq 1 ] || { usage; exit 2; }
    if [ -e "$MARKER" ] || [ -L "$MARKER" ]; then
      rm -f -- "$MARKER" || { echo "fm-buzz: cannot remove $MARKER; the bridge may still be on" >&2; exit 1; }
    fi
    if [ -e "$CHECK" ] || [ -e "$STATE/$FM_BUZZ_CHECK_ID.check-trust" ]; then
      unregister || { echo "fm-buzz: disabled, but could not unregister the watcher check (it stays inert)" >&2; exit 1; }
    fi
    echo "buzz bridge: disabled; no polling and no replies until bin/fm-buzz.sh enable"
    ;;
  status)
    [ "$#" -eq 1 ] || { usage; exit 2; }
    if fm_buzz_enabled; then echo "bridge: enabled"; else echo "bridge: disabled"; fi
    if fm_custom_check_registered "$STATE" "$FM_BUZZ_CHECK_ID" 2>/dev/null; then
      echo "watcher check: registered"
    else
      echo "watcher check: not registered"
    fi
    if fm_buzz_load_config; then
      echo "config: ok (community $BUZZ_COMMUNITY, channel $BUZZ_CHANNEL, owner $BUZZ_OWNER_PUBKEY, bridge $BUZZ_BRIDGE_PUBKEY)"
    else
      echo "config: $FM_BUZZ_CONFIG_ERROR"
    fi
    since=$(jq -r '.since // empty' "$STATE/buzz/cursor.json" 2>/dev/null) || since=
    echo "cursor: ${since:-none}"
    pending=0
    for f in "$STATE"/x-inbox/buzz-*.json; do
      [ -f "$f" ] && pending=$((pending + 1))
    done
    echo "pending requests: $pending"
    if [ -f "$STATE/buzz/poll.error" ]; then
      echo "last poll diagnostic: $(head -n1 "$STATE/buzz/poll.error")"
    fi
    ;;
  -h|--help) usage; exit 0 ;;
  *) usage; exit 2 ;;
esac
